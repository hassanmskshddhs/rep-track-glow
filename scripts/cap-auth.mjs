import { chromium } from 'playwright';
const b = await chromium.launch({executablePath:'/usr/bin/google-chrome-stable',args:['--no-sandbox']});
const c = await b.newContext({viewport:{width:390,height:844}});
const p = await c.newPage(); const errors=[]; p.on('pageerror',e=>errors.push(e.message));
await p.route('**/rest/v1/**', (route) => route.fulfill({ status: 200, contentType: 'application/json', body: '[]' }));
await p.goto('http://localhost:8082/', {waitUntil:'networkidle'});
await p.waitForTimeout(1500);
await p.screenshot({path:'/downloads/NAT-82-Welcome.png'});
await p.locator('text=Get started').first().click({force:true});
await p.waitForTimeout(1200);
await p.screenshot({path:'/downloads/NAT-83-Login.png'});
await p.locator('text=Sign up').first().click({force:true});
await p.waitForTimeout(600);
await p.screenshot({path:'/downloads/NAT-84-Signup.png'});
console.log('errors:', errors.slice(0,3));
await b.close();
